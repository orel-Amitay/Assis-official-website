import type { KnowledgeCategory, KnowledgeQaItem, KnowledgeSection } from "./review-state";
import type { TopicGroupId } from "./types";

function qa(question: string, example = ""): KnowledgeQaItem {
  return {
    question,
    answer: example,
    approval: "pending",
    availableForAgents: true,
    availableForCustomers: true,
  };
}

function section(detailName: string, questions: Array<string | [string, string]>): KnowledgeSection {
  return {
    detailName,
    needsReview: true,
    detailContent: questions.map((item) => (Array.isArray(item) ? qa(item[0], item[1]) : qa(item))),
  };
}

